/*
 * Host-side generator for kyber_kat.h.
 *
 * Built natively with -DKECCAK_SW (reference software Keccak) and runs the same deterministic
 * sequence as test_keys() in hornet_kyber.c: keypair, enc, dec from the fixed randombytes seed.
 * The firmware recomputes these on the SoC with the accelerator and compares.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "../kem.h"
#include "../fips202.h"

static void print_array(FILE *f, const char *name, const uint8_t *x, size_t len)
{
  size_t i;

  fprintf(f, "static const uint8_t %s[%zu] = {", name, len);
  for(i = 0; i < len; i++)
    fprintf(f, "%s0x%02x", (i == 0) ? "\n  " : (i % 12) ? ", " : ",\n  ", x[i]);
  fprintf(f, "\n};\n\n");
}

int main(void)
{
  uint8_t pk[CRYPTO_PUBLICKEYBYTES];
  uint8_t sk[CRYPTO_SECRETKEYBYTES];
  uint8_t ct[CRYPTO_CIPHERTEXTBYTES];
  uint8_t key_a[CRYPTO_BYTES];
  uint8_t key_b[CRYPTO_BYTES];
  uint8_t h[32];

  crypto_kem_keypair(pk, sk);
  crypto_kem_enc(ct, key_b, pk);
  crypto_kem_dec(key_a, ct, sk);

  if(memcmp(key_a, key_b, CRYPTO_BYTES)) {
    fprintf(stderr, "gen_kat: shared secrets differ\n");
    return 1;
  }

  printf("/* Generated by gen_kat.c (software Keccak, %s) - do not edit */\n", CRYPTO_ALGNAME);
  printf("#ifndef KYBER_KAT_H\n#define KYBER_KAT_H\n\n#include <stdint.h>\n\n");
  sha3_256(h, pk, sizeof(pk));
  print_array(stdout, "KAT_PK_SHA3_256", h, sizeof(h));
  sha3_256(h, sk, sizeof(sk));
  print_array(stdout, "KAT_SK_SHA3_256", h, sizeof(h));
  sha3_256(h, ct, sizeof(ct));
  print_array(stdout, "KAT_CT_SHA3_256", h, sizeof(h));
  print_array(stdout, "KAT_SS", key_a, sizeof(key_a));
  printf("#endif\n");

  return 0;
}
