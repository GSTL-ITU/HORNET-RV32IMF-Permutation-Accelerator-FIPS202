/*
 * Host-side generator for sphincs_kat.h.
 *
 * Built natively with the reference software Keccak (sphincsplus/ref/fips202.c) and runs the same
 * deterministic sequence as hornet_sphincs.c: message, keypair and signature from the fixed
 * randombytes seed. The firmware recomputes these on the SoC with the accelerator and compares.
 */
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "api.h"
#include "params.h"
#include "fips202.h"
#include "randombytes.h"

#define MLEN 32
#define XOF_LEN 300

static void print_array(FILE *f, const char *name, const uint8_t *x, size_t len)
{
  size_t i;

  fprintf(f, "static const uint8_t %s[%zu] = {", name, len);
  for(i = 0; i < len; i++)
    fprintf(f, "%s0x%02x", (i == 0) ? "\n  " : (i % 12) ? ", " : ",\n  ", x[i]);
  fprintf(f, "\n};\n\n");
}

int main(void)
{
  static uint8_t sig[SPX_BYTES];
  uint8_t pk[SPX_PK_BYTES];
  uint8_t sk[SPX_SK_BYTES];
  uint8_t m[MLEN];
  uint8_t msg[200];
  uint8_t out[XOF_LEN];
  uint8_t h[32];
  size_t siglen;

  printf("/* Generated by gen_kat.c (software Keccak, %s) - do not edit */\n", xstr(PARAMS));
  printf("#ifndef SPHINCS_KAT_H\n#define SPHINCS_KAT_H\n\n#include <stdint.h>\n\n");

  /* SHAKE256 over 200 bytes of 0xa3, 300 bytes out (multi-block absorb and squeeze) */
  memset(msg, 0xa3, sizeof(msg));
  shake256(out, XOF_LEN, msg, sizeof(msg));
  print_array(stdout, "KAT_SHAKE256_A3", out, XOF_LEN);

  randombytes(m, MLEN);
  if(crypto_sign_keypair(pk, sk) ||
     crypto_sign_signature(sig, &siglen, m, MLEN, sk) ||
     siglen != SPX_BYTES ||
     crypto_sign_verify(sig, siglen, m, MLEN, pk)) {
    fprintf(stderr, "gen_kat: SPHINCS+ sign/verify failed\n");
    return 1;
  }

  print_array(stdout, "KAT_M", m, MLEN);
  print_array(stdout, "KAT_PK", pk, sizeof(pk));
  print_array(stdout, "KAT_SK", sk, sizeof(sk));
  shake256(h, 32, sig, siglen);
  print_array(stdout, "KAT_SIG_SHAKE256", h, sizeof(h));
  printf("#endif\n");

  return 0;
}
